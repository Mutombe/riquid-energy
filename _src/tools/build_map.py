"""Builds assets/js/map-data.js: a dot grid filling Zimbabwe plus a simplified outline path.

Run: python _src/tools/build_map.py
"""
import json, os
import numpy as np

HERE = os.path.dirname(__file__)
geo = json.load(open(os.path.join(HERE, "zimbabwe.geojson")))
ring = np.array(geo["features"][0]["geometry"]["coordinates"][0])
lon0, lon1, lat0, lat1 = 25.1, 33.2, -22.6, -15.5
K = np.cos(np.radians(19))          # equirectangular, true at 19 S
W = 1000
scale = W / ((lon1 - lon0) * K)
H = round((lat1 - lat0) * scale)

def proj(lon, lat):
    return (lon - lon0) * K * scale, (lat1 - lat) * scale

def inside(x, y, poly):
    xs, ys = poly[:, 0], poly[:, 1]
    xj, yj = np.roll(xs, 1), np.roll(ys, 1)
    c = ((ys > y) != (yj > y)) & (x < (xj - xs) * (y - ys) / (yj - ys + 1e-12) + xs)
    return c.sum() % 2 == 1

px = np.array([proj(*pt) for pt in ring])
step = 15
dots = []
for y in np.arange(step / 2, H, step):
    for x in np.arange(step / 2, W, step):
        if inside(x, y, px):
            dots.append((round(x), round(y)))
# simplified outline (every 3rd vertex)
pts = px[::3]
path = "M" + " L".join(f"{x:.0f} {y:.0f}" for x, y in pts) + " Z"
cities = {
    "Harare": (31.052, -17.829), "Bulawayo": (28.58, -20.15), "Mutare": (32.67, -18.97),
    "Gweru": (29.82, -19.45), "Masvingo": (30.83, -20.07), "Victoria Falls": (25.84, -17.93),
    "Kariba": (28.80, -16.52), "Chinhoyi": (30.20, -17.36), "Marondera": (31.55, -18.19),
    "Kwekwe": (29.81, -18.93), "Bindura": (31.33, -17.30), "Chiredzi": (31.67, -21.05),
    "Hwange": (26.50, -18.36), "Beitbridge": (30.00, -22.22),
}
cj = {k: [round(v) for v in proj(*ll)] for k, ll in cities.items()}
js = ("/* generated by _src/tools/build_map.py */\nwindow.RIQUID_MAP = " +
      json.dumps({"w": W, "h": H, "step": step, "dots": dots, "outline": path, "cities": cj}, separators=(",", ":")) + ";\n")
open(os.path.join(HERE, "..", "..", "assets", "js", "map-data.js"), "w").write(js)
print(W, H, len(dots), "dots", len(js) // 1024, "KB")
